using System.Collections.Generic;
using System.Linq;
using System.Text;
using FinanceTracker.Generated.Shared;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace FinanceTracker.Generated.DependencyInjection;

/// <summary>
/// The project's own <c>Program</c>, the server's or the front end's, which the generated registrations extend.
/// </summary>
internal sealed class RegistrationProgram
{
    private readonly INamedTypeSymbol _program;

    private RegistrationProgram(INamedTypeSymbol program, string destination)
    {
        _program = program;
        Destination = destination;
    }

    /// <summary>
    /// The project's <c>FinTrackServiceDestination</c>, the <c>ServiceDestinationType</c> it registers.
    /// </summary>
    public string Destination { get; }

    /// <summary>
    /// The project's <c>Program</c>, <see langword="null"/> without one or without a destination.
    /// </summary>
    public static RegistrationProgram? Find(Compilation compilation, AnalyzerConfigOptionsProvider options)
    {
        // Skip if there is no Service Destination MSBuildProperty, not code in need of processing.
        if (!options.GlobalOptions.TryGetValue(
                $"build_property.{SourceGeneratorConstants.ServiceDestinationProperty}", out string? destination) ||
            string.IsNullOrWhiteSpace(destination))
        {
            return null;
        }

        INamedTypeSymbol? program = compilation.GetTypeByMetadataName($"{compilation.AssemblyName}.Program");
        return program is null ? null : new RegistrationProgram(program, destination.Trim());
    }

    /// <summary>
    /// A part of <c>Program</c> with a <paramref name="methodName"/> registering the <paramref name="types"/>.
    /// </summary>
    public SourceText Write(string methodName, IEnumerable<InjectableType> types)
    {
        List<InjectableType> all = types.ToList();
        HashSet<string> shared = SharedServiceTypes(all);

        string registrations = string.Join("\n            ", all
            .OrderBy(static x => x.ServiceType)
            .ThenBy(static x => x.ImplementationType)
            .Select(x => Registration(x, shared)));

        string modifiers = _program.IsStatic ? "public static partial" : "public partial";

        string code = $$"""
                        // <auto-generated/>
                        using Microsoft.Extensions.DependencyInjection;
                        using Microsoft.Extensions.DependencyInjection.Extensions;

                        namespace {{_program.ContainingNamespace.ToDisplayString()}}
                        {
                            {{modifiers}} class Program
                            {
                                public static void {{methodName}}(IServiceCollection services)
                                {
                                    {{registrations}}
                                }
                            }
                        }
                        """;

        return SourceText.From(code, Encoding.UTF8);
    }

    /// <summary>
    /// The service types more than one class is registered as, e.g. each check a sync runs.
    /// </summary>
    private static HashSet<string> SharedServiceTypes(IEnumerable<InjectableType> types) =>
        new(types
            .GroupBy(static x => x.ServiceType)
            .Where(static x => x.Select(static type => type.ImplementationType).Distinct().Count() > 1)
            .Select(static x => x.Key));

    /// <summary>
    /// One registration, unless one's already there. A service type several classes share gets each of them,
    /// resolved together as an <c>IEnumerable</c>, the rest only the first, so one registered before wins.
    /// </summary>
    private static string Registration(InjectableType type, HashSet<string> shared)
    {
        if (shared.Contains(type.ServiceType))
        {
            return $"services.TryAddEnumerable(ServiceDescriptor.{type.Lifetime}<{type.ServiceType}, " +
                   $"{type.ImplementationType}>());";
        }

        return $"services.TryAdd{type.Lifetime}<{type.ServiceType}, {type.ImplementationType}>();";
    }
}
